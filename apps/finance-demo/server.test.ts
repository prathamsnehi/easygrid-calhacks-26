import test from 'node:test';
import assert from 'node:assert/strict';
import {applyAction,snapshot} from './server.ts';

test('finance UI server adapter calls real CAL-37/38/39 reducers and rejects early actions',()=>{
 applyAction('reset');
 assert.equal(snapshot().approved,false);
 assert.throws(()=>applyAction('complete'),/approval|20%|settlement/i);
 assert.throws(()=>applyAction('rent'),/clock/i);
 applyAction('approve');
 assert.throws(()=>applyAction('approve'),/already/i);
 applyAction('first_fail');
 assert.equal(snapshot().firstPaid,false);
 assert.equal(snapshot().firstLedger.filter(x=>x.status==='attempted').length,2);
 applyAction('first');
 assert.equal(snapshot().firstPaid,true);
 assert.equal(snapshot().firstLedger.filter(x=>x.status==='paid').length,2);
 assert.throws(()=>applyAction('first'),/already|paid/i);
 applyAction('complete');
 assert.equal(snapshot().completed,true);
 assert.throws(()=>applyAction('complete'),/already/i);
 applyAction('balance_fail');
 assert.equal(snapshot().balancePaid,false);
 applyAction('balance');
 assert.equal(snapshot().balancePaid,true);
 assert.equal(snapshot().later.payments.filter(x=>x.kind==='completion_balance'&&x.status==='paid').reduce((n,x)=>n+x.amountCents,0),1600000);
 assert.throws(()=>applyAction('balance'),/already/i);
 applyAction('advance');
 assert.equal(snapshot().dueDate,'2026-11-24');
 applyAction('rent');
 assert.equal(snapshot().later.payments.filter(x=>x.kind==='monthly_fee').length,2);
 assert.throws(()=>applyAction('rent'),/already/i);
 applyAction('advance');
 assert.equal(snapshot().dueDate,'2026-12-24');
 applyAction('mismatch');
 const s=snapshot();
 assert.equal(s.later.payments.filter(x=>x.kind==='monthly_fee').length,4);
 assert.equal(s.later.discrepantCents,5000);
 assert.equal(s.later.paidCents,1670000);
 assert.equal(s.later.expectedCents,1700000);
 assert.throws(()=>applyAction('mismatch'),/already/i);
 applyAction('reset');
 assert.equal(snapshot().later.payments.length,0);
});
